#: Instruction budget for a long program. The original needs about 40 million instructions for
#: 92 live instructions, its work grows faster than the program, and the 20 million default
#: would stop it first (a slow run, not a runaway).
SLOW_BUDGET = 400_000_000


def _slow() -> list[Case]:
    source = VS + b"mov r0, v0\n" + b"add r0, r0, c0\n" * 90 + b"mov oPos, r0\n"
    note = "92 instructions expand to 138 microcode words, the limit is 136 (error V600)"
    return [
        Case("syntax_vs_microcode_over_limit", "malformed", source, TEXT_FLAGS, note, SLOW_BUDGET)
    ]


def _overruns() -> list[Case]:
    """Sources the original compiles by writing past the end of its 240 byte output block.

    Instruction index 15 and above store a combiner word at `output + 0xB4 + 4 * index`, with
    no bound check (T485), so from the 16th instruction on the store lands on whatever follows
    the block. The reference heap has spare bytes there, so the original returns, and the
    reference measures the overrun (`verify.Measurement.heap_overrun`) and does not compare.
    """
    sources = {
        "ps_sixteen_instructions": (
            PS + b"mul r0, r0, v0\n" * 16,
            "the first count that overruns the output block by one word",
        ),
        "ps_twenty_instructions": (
            PS + b"mul r0, r0, v0\n" * 20,
            "five words past the output block, the native compiler returns once then faults",
        ),
    }
    return [
        _case(f"overrun_{name}", "malformed", source, note)
        for name, (source, note) in sources.items()
    ]


def _throws() -> list[Case]:
    return [
        _case("throw_version_only", "malformed", b"vs.1.1\n", "vertex version, no instructions"),
        _case("throw_version_no_newline", "malformed", b"vs.1.1", "version without a newline"),
    ]


def _flags() -> list[Case]:
    source = VS + MOV
    return [
        _case(f"flags_{flag:#x}", "malformed", source, f"text source with flags {flag:#x}", flag)
        for flag in (0x1, 0x2, 0x4, 0x8, 0x10, 0x20, 0x100, 0x120, 0xFFFFFFFF)
    ]


def corpus() -> list[Case]:
    """Every case, in a stable order, with unique names."""
    cases = [*_controls(), *_syntax(), *_slow(), *_overruns(), *_throws(), *_flags()]
    names = [case.name for case in cases]
    if len(names) != len(set(names)):
        raise ValueError("duplicate text corpus case name")
    return cases
