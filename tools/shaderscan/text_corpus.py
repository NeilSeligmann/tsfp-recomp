"""A deterministic corpus of valid and malformed ASCII `XGAssembleShader` sources (T385).

The T202 corpus (`malformed.py`) is binary vertex tokens with every optional output NULL.
This one is the text path (flags 0): vertex and pixel sources written as assembler text, run
with the constants output and the compilation-errors output supplied, so a failing source
also yields the assembler's own message text, and a `def` yields its constants buffer.

Every source is synthetic, nothing is derived from the disc, so the corpus can be committed
and regenerated by anyone. As in `malformed.py` no expected behaviour is stored: what the
original does is measured by running its bytes (`tools.shaderscan.assemble`) and what the
native route does by `tools.shaderscan.native_corpus`. `group` records the INTENT of a case.
"""

from __future__ import annotations

from tools.shaderscan.malformed import Case

#: Text sources are assembled with no flags (the title's own text call site passes 0).
TEXT_FLAGS = 0

VS = b"vs.1.1\n"
PS = b"ps.1.1\n"
MOV = b"mov oPos, v0\n"


def _case(name: str, group: str, source: bytes, note: str, flags: int = TEXT_FLAGS) -> Case:
    return Case(name, group, source, flags, note)


