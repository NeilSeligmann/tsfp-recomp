"""Mutations for the OUTPUT STATE groups of the pushbuffer replay (T267): the decoder's output-state
shadow (`src/gpu/gpu_pgraph.c`), their resolution into Vulkan state (`src/gpu/gpu_pgraph_replay.c`), the
Vulkan side (`src/gpu/gpu_vsh_draw.c`) and the swap replay's opt-in (`src/gpu/d3d8_swap_replay.c`).

Grouped by what a survivor would let through, one section per state group (added by the commit that
adds the group):

    table      a method number one slot off, a word in the wrong group: the failure
               `docs/d3d8-usage.md` 2.1 records (a real method on the wrong slot, every row plausible)
    optin      the opt-in itself: a group decoded while off turns a refusal into silence, a group kept
               when the caller dropped it, a stale bit that is not a group
    brackets   state written inside a BEGIN_END bracket describes the wrong draw
    snapshots  a state write that does not force a new snapshot replays a draw against a later state
    resolve    every refusal and every number handed to Vulkan, each with the test that names it
    vulkan     the scissor/state actually reaching the pipeline (device-only kills are `needs_device`)
    swap       the swap replay's config reaching the model and the backend

The kills are by `test_gpu_pgraph_state` (decode, resolve, pixels on every device), `test_d3d8_gpu_state`
(the real emitters over a real ring, no device) and `test_d3d8_swap_replay` (the whole path).

DEVICE-DEPENDENT kills (exit 77 without a Vulkan device) are reported SKIPPED by the harness, never
killed. `_NEEDS_DEVICE` at the bottom records which ones (120 of the set, from a no-device run).

RESULT (T267, RADV and llvmpipe, `c_suites.py --prefix gpu-state-`, 2026-10-03): the whole set was run against the commit
before the last fix, 369 of 373 killed, the four that were not are all addressed in the set as it stands: `depth-pipeline-write`
removed as equivalent (below), `clear-end-bound` did not compile (an unused parameter, now written so it does), `swap-clear-first` and
`swap-clear-range-check` (a redundant check in the swap replay, removed, gpu_pgraph_replay_pass already refuses the same range) got a test and a
deletion. The rows changed after that run were re-run on their own (see docs/tasks.md T267).

REMOVED AS EQUIVALENT (a mutant no test can kill, which a survivor list must not carry): the depth and stencil attachments' load op
and store op set to DONT_CARE (undefined by the Vulkan specification, and RADV and llvmpipe keep the uploaded contents all the same, so
only a driver that discards them would show it), and `stencil-nothing-written` (a stencil state with no word written resolves from the
all-default words, which are ALWAYS and KEEP, i.e. to nothing, so the early return is an optimisation and not a behaviour), and
`depth-pipeline-write` (the pipeline's `depthWriteEnable` without the `depth_test &&` guard: Vulkan itself disables depth writes
whenever `depthTestEnable` is false, so the guard changes nothing an observer can see).

Every `old` here is checked to occur exactly once by `tests/test_mutation_anchors.py`.
"""

