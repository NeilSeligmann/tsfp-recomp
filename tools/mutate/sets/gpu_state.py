def _row(file: str, mutation_id: str, old: str, new: str, why: str, targets: list[str]) -> dict:
    return {
        "id": f"gpu-state-{mutation_id}",
        "file": file,
        "old": old,
        "new": new,
        "targets": list(targets),
        "why": why,
    }


def _pg(mutation_id: str, old: str, new: str, why: str, targets: list[str] | None = None) -> dict:
    return _row(_PGRAPH, mutation_id, old, new, why, targets or _DECODE)


